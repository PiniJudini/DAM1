pais = input("Ingrese su pais: ")
paisminusculas = pais.lower()
if (paisminusculas == "francia"):
    print("Su capital es Paris")
elif (paisminusculas == "italia"):
    print("Su capital es Roma")
elif (paisminusculas == "japon" or paisminusculas == "japón"):
    print("Su capital es Tokyo")
elif (paisminusculas == "chile"):
    print("Su capital es Santiago de Chile")